// protected-paths.mjs — decides whether a file write touches a generated path

import { basename, isAbsolute, relative, resolve, sep } from "node:path";
import { DOMAIN_DIRS } from "./exercise.mjs";

// Run logs are the evidence RESULT.md quotes; output/ is what the program writes.
// Both sit directly in an exercise folder: <domain>/<task-id>_<title>/Log/.
const EXERCISE_DIRS = ["log", "output"];
const DOMAINS = DOMAIN_DIRS.map((d) => d.toLowerCase());
// npm regenerates node_modules/ wherever it sits.
const ANY_DEPTH_DIRS = ["node_modules"];
// package-lock.json changes only through npm.
const LOCK_FILE = "package-lock.json";

/** .env and .env.local, .env.production...: secrets. The committed template is example.env. */
const isEnvFile = (name) => name === ".env" || (name.startsWith(".env.") && name !== ".env.example");

/**
 * Rewrites Windows path forms that name the same file in another spelling, so the
 * checks below see a plain drive path: /f/x (Git Bash), \\?\F:\x and \\.\F:\x (device
 * paths), \\?\UNC\host\F$\x and \\host\F$\x (admin share, any host name, since the
 * machine's own name and ::1 reach it too), and x::$DATA or x:stream (data streams).
 */
export function canonical(filePath) {
  let p = filePath.replace(/^\/([a-z])(?=\/|$)/i, "$1:").replace(/\//g, "\\");
  p = p.replace(/^\\\\[?.]\\UNC\\/i, "\\\\");
  p = p.replace(/^\\\\[?.]\\(?=[a-z]:)/i, "");
  p = p.replace(/^\\\\[^\\]+\\([a-z])\$(?=\\|$)/i, "$1:");
  // Any colon after the drive letter starts a stream name; the file is what precedes it.
  const drive = /^[a-z]:/i.exec(p)?.[0] ?? "";
  return drive + p.slice(drive.length).replace(/:[^\\]*/g, "");
}

/**
 * Returns why `filePath` must not be written by hand, or undefined when the write is fine.
 * Relative paths resolve against `cwd`. Paths outside `root` are not this repo's business.
 * Names compare case-insensitively: on Windows, LOG/ and Log/ are the same folder.
 */
export function protectionReason(filePath, root, cwd = root) {
  const target = process.platform === "win32" ? canonical(filePath) : filePath;
  const rel = relative(root, resolve(cwd, target));
  if (!rel || rel === ".." || rel.startsWith(`..${sep}`) || isAbsolute(rel)) return undefined;

  const segments = rel.split(sep).map((s) => s.toLowerCase());
  const name = segments.pop();
  if (isEnvFile(name)) return `${rel} holds secrets. Edit it yourself; Claude does not write it.`;
  if (name === LOCK_FILE) return `${rel} is generated by npm. Change package.json and run npm install instead.`;

  if (segments.some((s) => ANY_DEPTH_DIRS.includes(s))) {
    return `${rel} is under node_modules/, which npm generates. Change package.json instead.`;
  }
  // segments[0] is the domain folder, segments[1] the exercise, segments[2] its Log/ or output/.
  if (segments.length >= 3 && DOMAINS.includes(segments[0]) && EXERCISE_DIRS.includes(segments[2])) {
    return segments[2] === "log"
      ? `${rel} is a run log. Logs are evidence: read them, never edit them.`
      : `${rel} is program output. Change the code that writes it instead.`;
  }
  return undefined;
}
